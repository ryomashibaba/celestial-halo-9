#!/usr/bin/env python3
"""D48 R4 visual-feedback production gate. STANDARD LIBRARY ONLY.

This checker is a workflow-safety and evidence tool, NOT an artist, Blender
installation, local MCP connection, finished City Master, or art quality rater.
Use with actual saved native BLEND, 7+ camera PNG, before/after image reviews,
and genuinely altered meshes. It will reject repeated blind batch generation.
"""
import argparse
import hashlib
import json
from pathlib import Path

PROGRAM_SCOPE = ["M247-C", "W0"] + [f"H{i}" for i in range(1, 7)] + [
    f"SB{i:02d}" for i in range(1, 17)] + [f"V{i}" for i in range(1, 4)] + [
    f"METRO_AXIS_{i}" for i in range(1, 4)]
REQUIRED_VIEW_TYPES = (
    "urban_aerial", "central_front", "central_rear", "east_seafront",
    "human_street", "human_public_interior", "human_sky_district")
LOCKED = {
    "project": "CELESTIAL HALO-9 / CELESTIAL SPINE",
    "city_master_3d_first": True,
    "world_write_allowed": False,
    "formal_design_adoption": False,
    "user_approved_work_local_control": False,
    "outsourced_concept_art": False,
    "official_shared_coordinates_verified": False,
    "official_model_height_to_mc_y_verified": False,
    "art_reject_history_not_used_as_master": True,
    "exception_private_interiors_only": True,
}
PRIOR_REJECTED = ("D48_R1", "D48_R2_P0", "D48_R2_P1", "D48_R2_P2",
                  "D48_R3_G1", "D48_R3_G2")
VISUAL_REQUIREMENTS = {
    "macro":"One joined civilization at ~10km: central protagonist, W0 mountain/cliff/sea and 6 sky cities",
    "central":"Original M247-C alpha double shell and beta diagonal broken city spine: sacred 80%, danger 20%",
    "public":"Actual 100m-class deep public interior and reachable entrances, not wall labels",
    "inhabited":"Each H1-H6 must become thick, legible lived-in city neighborhoods, not floating shelves",
    "special":"16 distinct SB01-SB16 detailed 3D public/special interiors are NOT optional",
    "urban":"All ordinary exteriors; streets, underground public rooms, stations, bridges, light, landscape",
    "access":"Street-to-public-room and street-to-sky neighborhood 3D walkability/transport separately certified",
}
class GateError(ValueError): pass
def strict(condition,reason):
    if not condition: raise GateError(reason)
def canonical_json(data):
    return json.dumps(data,ensure_ascii=False,sort_keys=True,separators=(",",":"))
def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def template():
    return {
      "schema":"halo9.d48.r4.visual-feedback.v1",
      "status":"PREFLIGHT_ONLY_NO_NEW_ART",
      "basis":"NEW_BLENDER_SCENE_REQUIRED_NOT_D48_REJECTED_REGEN",
      "source_branch":"research/r33-s27-d48-r4-visual-authoring-method-20261031",
      "formal_adoption":False,"minecraft_write":False,"city_master_complete":False,
      "official_coordinates_verified":False,
      "work_local_control_authorized":False,
      "scope":PROGRAM_SCOPE,
      "locked":LOCKED,
      "required_visual_dimensions":VISUAL_REQUIREMENTS,
      "camera_types":list(REQUIRED_VIEW_TYPES),
      "stages":[
         {"id":"A","state":"PENDING","description":"Native BLEND visually authored: true inhabited mass, void, public entrance and sky-city attachment, not generated by old parameter extrusion"},
         {"id":"B","state":"PENDING","description":"Actual initial BLEND and at least 7 real camera images, in same scene"},
         {"id":"C","state":"PENDING","description":"AI/direct human perceptual review based on actual inspected images, with exact file hashes, named visual failures and next mesh/object edit targets"},
         {"id":"D","state":"PENDING","description":"Reopen the SAME saved native BLEND. Sculpt/boolean/remodel source geometry in AI-operated Blender GUI or MCP; original remains immutable"},
         {"id":"E","state":"PENDING","description":"Same 7 cameras AFTER images; independent mesh diff; AI reviews aesthetic result before any detail/quantity expansion"}],
      "art":"UNREVIEWED_NOT_PASSED",
      "function":"UNCERTIFIED",
      "source_blend":None,
      "source_sha256":None,
      "images":[],
      "review":None,
      "modified_native_scene":None,
      "edit_audit":None,
    }
def validate(plan,repo=None,stage="preflight"):
    strict(plan.get("schema")=="halo9.d48.r4.visual-feedback.v1","schema")
    strict(plan.get("scope")==PROGRAM_SCOPE,"Entire 30-entity scope must remain fixed and complete")
    strict(plan.get("locked")==LOCKED,"A locked constitution/safety setting changed")
    strict(plan.get("required_visual_dimensions")==VISUAL_REQUIREMENTS,"Art/urban standard changed")
    strict(plan.get("camera_types")==list(REQUIRED_VIEW_TYPES),"All seven view types required")
    for field in ("formal_adoption","minecraft_write","city_master_complete",
                  "official_coordinates_verified","work_local_control_authorized"):
        strict(plan.get(field) is False,"This research gate cannot declare "+field)
    strict(plan.get("basis")=="NEW_BLENDER_SCENE_REQUIRED_NOT_D48_REJECTED_REGEN",
           "Rejected R1/R2/R3 geometry cannot become R4 official art master")
    strict(plan.get("art") in ("UNREVIEWED_NOT_PASSED","REJECT","HOLD"),
           "Art cannot be automated to PASS")
    strict(plan.get("function")=="UNCERTIFIED","Function has not been independently tested")
    stages=plan.get("stages")
    strict(isinstance(stages,list) and [s.get("id") for s in stages]==list("ABCDE"),
           "A-E order and provenance are mandatory")
    states=[s.get("state") for s in stages]
    strict(all(x in ("PENDING","DONE") for x in states),"Stage state invalid")
    strict(all(states[i]=="DONE" or states[i+1]=="PENDING" for i in range(4)),
           "Stage completion cannot skip prerequisites")
    if stage=="preflight":
        strict(plan["status"]=="PREFLIGHT_ONLY_NO_NEW_ART","Preflight has NO fresh artwork")
        strict(all(state=="PENDING" for state in states),"Nothing can claim completed without evidence")
        strict(plan["source_blend"] is None and not plan["images"],"Preflight has no native evidence")
    if stage in ("reviewed","postedit"):
        for i in range(3):
            strict(states[i]=="DONE","Actual native source/cameras/review required")
        strict(plan["source_blend"] and plan["source_sha256"],"Native source and digest required")
        images=plan.get("images")
        strict(isinstance(images,list) and len(images)>=7,"Actual 7+ images required")
        strict(set(x.get("view") for x in images)>=set(REQUIRED_VIEW_TYPES),"Required views absent")
        strict(all(isinstance(x.get("sha256"),str) and len(x["sha256"])==64
                   for x in images),"Each image needs a real immutable digest")
        review=plan.get("review") or {}
        strict(review.get("inspected_source_sha256")==plan["source_sha256"],
               "Review must match exact native BLEND")
        strict(isinstance(review.get("observed_visual_failures"),list)
               and review["observed_visual_failures"],"AI actually inspected images; note concrete problems")
        strict(isinstance(review.get("target_mesh_names"),list)
               and review["target_mesh_names"],"Actual source object targets required")
        strict(review.get("art_pass_claimed") is False,"No automatically invented art pass")
    if stage=="postedit":
        strict(all(x=="DONE" for x in states),"G1 real edits and re-review must be complete")
        edited=plan.get("modified_native_scene") or {}
        audit=plan.get("edit_audit") or {}
        strict(edited.get("native_blend_sha256")!=plan["source_sha256"]
               and isinstance(edited.get("native_blend_sha256"),str)
               and len(edited["native_blend_sha256"])==64,"A truly modified Blender source required")
        strict(audit.get("same_original_camera_matrix_hashes") is True
               and audit.get("untargeted_real_meshes_unchanged") is True
               and audit.get("source_original_hash_unchanged") is True,
               "No fake view change, protected mesh edits or overwritten originals")
        strict(audit.get("actual_target_geometry_modified") is True,"Existing mesh really must change")
        strict(audit.get("rerendered_same_camera_actual_blender") is True,"New real source images required")
    if repo is not None:
        doc=repo/"docs/policy/PROJECT_CONSTITUTION.md"
        standard=repo/"docs/policy/CITY_MASTER_3D_STANDARD.md"
        strict(doc.is_file() and standard.is_file(),"Cannot verify project's immutable policies")
        d=doc.read_text(encoding="utf-8");s=standard.read_text(encoding="utf-8")
        strict("ART-FIRST" in d and "CITY MASTER 3D FIRST" in d,"Constitution mismatch")
        strict("一般建物の内部" in s and "SB01" in s and "H1" in s,"Missing city-master standards")
    return {"result":"LIMITED_SCHEMA_AND_POLICY_PASS_NOT_ART","stage":stage,"scope_count":len(PROGRAM_SCOPE),
            "art":plan["art"],"minecraft_write":False}
def selftest(repo=None):
    import copy
    good=template()
    validate(good,repo)
    def must_fail(mutator,stage="preflight"):
        d=copy.deepcopy(good);mutator(d)
        try: validate(d,repo,stage)
        except GateError: return
        raise AssertionError("Unsafe/unsupported state erroneously approved")
    must_fail(lambda d:d.update({"minecraft_write":True}))
    must_fail(lambda d:d["scope"].pop())
    must_fail(lambda d:d["camera_types"].pop())
    must_fail(lambda d:d["locked"].update({"user_approved_work_local_control":True}))
    must_fail(lambda d:d.update({"art":"PASS"}))
    must_fail(lambda d:d["stages"][3].update(state="DONE"))
    must_fail(lambda d:d.update({"basis":"D48_R3_G2_REJECTED_COPY"}))
    must_fail(lambda d:d.update({"status":"COMPLETED"}))
    must_fail(lambda d:d.update({"source_blend":"invented.blend"}))
    must_fail(lambda d:d.update({"review":{"art_pass_claimed":True}}),"reviewed")
    return {"selftest":"10_NEGATIVE_TESTS_PASS","new_art_created":False,
            "user_PC_accessed":False,"mcp_connected":False,"scope_count":len(PROGRAM_SCOPE)}
def main():
    a=argparse.ArgumentParser()
    a.add_argument("--init",metavar="PATH")
    a.add_argument("--validate",metavar="PATH")
    a.add_argument("--selftest",action="store_true")
    a.add_argument("--repo",type=Path)
    args=a.parse_args()
    if args.init:
        Path(args.init).parent.mkdir(parents=True,exist_ok=True)
        Path(args.init).write_text(json.dumps(template(),ensure_ascii=False,indent=2)+"\n")
        print("R4_REVIEW_SESSION_PREPARED_NOT_EXECUTED",args.init)
    if args.validate:
        print(json.dumps(validate(json.loads(Path(args.validate).read_text()),args.repo),
                         ensure_ascii=False))
    if args.selftest:
        print(json.dumps(selftest(args.repo),ensure_ascii=False))
if __name__=="__main__": main()
